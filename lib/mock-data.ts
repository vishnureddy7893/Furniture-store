/** Kept for the original import path used by the homepage sections. */
export const mockProducts = products

export const productBySlug = (slug: string): MarbleProduct | undefined =>
  products.find((p) => p.slug === slug)

export const productsByCategory = (slug: CategorySlug): MarbleProduct[] =>
  products.filter((p) => p.categorySlug === slug)

export const featuredProducts = (count = 6): MarbleProduct[] =>
  products.filter((p) => p.isBestSeller || p.isNew).slice(0, count)

export const relatedProducts = (product: MarbleProduct, count = 3): MarbleProduct[] =>
  products
    .filter((p) => p.categorySlug === product.categorySlug && p.id !== product.id)
    .concat(products.filter((p) => p.categorySlug !== product.categorySlug))
    .slice(0, count)

export const discountPercent = (product: MarbleProduct): number =>
  product.oldPrice ? Math.round(((product.oldPrice - product.price) / product.oldPrice) * 100) : 0
